import { useSettings, useUpdateSettings } from '@hooks/useSettings';
import '@styles/PDF.css'


/**
 * TemplatePickerSection
 *
 * Drop this into SettingsPage wherever you want the template picker to appear.
 * It reads and writes settings.invoiceTemplate via the existing useSettings hooks.
 *
 * No props needed — it manages its own state via the query cache.
 */
const TEMPLATES = [
  {
    key: 'classic',
    label: 'Classic',
    description: 'Clean table layout matching the traditional bill format. Ideal for contractors, electricians, and trades.',
    preview: '📄',
  },
  {
    key: 'modern',
    label: 'Modern',
    description: 'Branded header with accent color. Looks professional for consultants, agencies, and B2B invoicing.',
    preview: '🎨',
  },
];

const TemplatePickerSection = () => {
  const { data: settings } = useSettings();
  const { mutate: updateSettings, isPending } = useUpdateSettings();

  const current = settings?.invoiceTemplate ?? 'classic';

  const handleSelect = (key) => {
    if (key === current || isPending) return;
    updateSettings({ invoiceTemplate: key });
  };

  const handleToggleGst = () => {
    updateSettings({ showGstBreakdown: !settings?.showGstBreakdown });
  };

  return (
    <div className="settings-section">
      <h3 className="settings-section-title">Invoice Template</h3>
      <p className="settings-section-desc">
        Choose the PDF layout for all invoices generated by your account.
      </p>

      <div className="template-picker-grid">
        {TEMPLATES.map((tpl) => {
          const isActive = current === tpl.key;
          return (
            <button
              key={tpl.key}
              className={`template-picker-card ${isActive ? 'template-picker-card--active' : ''}`}
              onClick={() => handleSelect(tpl.key)}
              disabled={isPending}
              aria-pressed={isActive}
              type="button"
            >
              <span className="template-picker-preview" aria-hidden="true">
                {tpl.preview}
              </span>
              <span className="template-picker-label">{tpl.label}</span>
              <span className="template-picker-desc">{tpl.description}</span>
              {isActive && (
                <span className="template-picker-badge">Active</span>
              )}
            </button>
          );
        })}

        <div className="settings-toggle-row">
          <div>
            <p className="settings-toggle-label">Show GST Breakdown</p>
            <p className="settings-toggle-desc">
              Display CGST / SGST / IGST columns on invoice PDF
            </p>
          </div>
          <button
            className={`toggle-btn ${settings?.showGstBreakdown ? 'toggle-btn--on' : ''}`}
            onClick={handleToggleGst}
            disabled={isPending}
            type="button"
            role="switch"
            aria-checked={settings?.showGstBreakdown}
          >
            <span className="toggle-thumb" />
          </button>
        </div>
      </div>

      {isPending && (
        <p className="settings-saving-hint">Saving…</p>
      )}
    </div>
  );
};

export default TemplatePickerSection;
